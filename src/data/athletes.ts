export function getAthleteById(id: string): Athlete | undefined {
  return ATHLETES.find((a) => a.id === id);
}

export function getDailyAthlete(): Athlete {
  const start = new Date('2025-01-01T00:00:00Z');
  const now = new Date();
  const utcToday = new Date(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()));
  const diffDays = Math.floor((utcToday.getTime() - start.getTime()) / 86_400_000);
  return ATHLETES[((diffDays % ATHLETES.length) + ATHLETES.length) % ATHLETES.length];
}

export function getTodayString(): string {
  const now = new Date();
  const y = now.getUTCFullYear();
  const m = String(now.getUTCMonth() + 1).padStart(2, '0');
  const d = String(now.getUTCDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function getDayNumber(): number {
  const start = new Date('2025-01-01T00:00:00Z');
  const now = new Date();
  const utcToday = new Date(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()));
  return Math.max(1, Math.floor((utcToday.getTime() - start.getTime()) / 86_400_000) + 1);
}

export function fuzzySearch(query: string): Athlete[] {
  if (!query || query.length < 2) return [];
  const q = query.toLowerCase().trim();
  return ATHLETES.filter((a) => {
    if (a.name.toLowerCase().includes(q)) return true;
    return a.aliases.some((alias) => alias.toLowerCase().includes(q));
  }).slice(0, 6);
}

export function normalizeGuess(guess: string): string {
  return guess
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s]/g, '');
}

export function isCorrectGuess(guess: string, athlete: Athlete): boolean {
  const normalized = normalizeGuess(guess);
  const nameParts = athlete.name.toLowerCase().split(' ');
  if (normalizeGuess(athlete.name) === normalized) return true;
  // Accept last name only if unambiguous (at least 4 chars)
  if (normalized.length >= 4 && nameParts.some((p) => normalizeGuess(p) === normalized)) return true;
  return athlete.aliases.some((alias) => normalizeGuess(alias) === normalized);
}
